    private MessageTranslations() {}

    public static String toEnglish(String message) {
        if (message == null) return null;
        String result = message;
        for (Map.Entry<String, String> e : FRAGMENTS.entrySet()) {
            if (result.contains(e.getKey())) result = result.replace(e.getKey(), e.getValue());
        }
        return result;
    }
